// Packages Pixelbolt Fluids for Aseprite.
//
//   node aseprite/build.mjs [--lua path/to/lua] [--skip-gates]
//
// 1. Reads the gas presets strictly (tools/presets.mjs): a field the Lua port doesn't implement stops the build,
//    naming the field.
// 2. Runs the parity gate (tools/parity.mjs, every pixel of every frame must match) for every live preset, and the
//    checks against a stand-in Aseprite API
//    (checks/run-checks.lua). Presets listed in prebaked.json ship Pixelbolt's own frames instead (8 seeds at the
//    defaults) and skip the gate.
// 3. Bundles the extension's modules and the presets into one Lua file, smoke-tests the bundle, and writes
//    aseprite/dist/pixelbolt-fluids-<version>.aseprite-extension, printing its SHA-256.
// Needs a Lua 5.4 interpreter: aseprite/.tools/lua(.exe) or --lua.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ROOT, PresetError, loadPresets, presetsModule, lua } from './tools/presets.mjs';

export const VERSION = '1.0.0';
export const NAME = 'pixelbolt-fluids';
const HERE = dirname(fileURLToPath(import.meta.url));
const EXTENSION = join(HERE, 'extension');
const DIST = join(HERE, 'dist');

// The extension's modules: every .lua file under extension/, named by its path without the extension.
export function moduleFiles(dir = EXTENSION) {
  const out = [];
  const walk = folder => {
    for (const entry of readdirSync(folder, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
      const file = join(folder, entry.name);
      if (entry.isDirectory()) walk(file);
      else if (entry.name.endsWith('.lua')) out.push({ name: relative(dir, file).replace(/\\/g, '/').replace(/\.lua$/, ''), file });
    }
  };
  walk(dir);
  return out;
}

// No module may reach for files, the OS or globals inside Aseprite: they would prompt the user or break bundling.
const FORBIDDEN = [/\brequire\s*\(/, /\bdofile\s*\(/, /\bloadfile\s*\(/, /\bio\./, /\bos\./, /\bdebug\./];
export function checkModule(name, text) {
  const code = text.replace(/--\[(=*)\[[\s\S]*?\]\1\]/g, '').replace(/--[^\n]*/g, '');
  for (const pattern of FORBIDDEN) if (pattern.test(code)) throw new Error(`extension/${name}.lua uses ${pattern.source.replace(/\\b|\\s\*|\\\(|\\\./g, '')}, which the extension must not`);
  if (!/^\s*local use = \.\.\./.test(code)) throw new Error(`extension/${name}.lua must start with "local use = ..."`);
}

export function bundle(modules, presets, commit) {
  const parts = [
    `-- Pixelbolt Fluids for Aseprite ${VERSION}: Pixelbolt's gas presets simulated in Aseprite.`,
    `-- Built from Pixelbolt ${commit} (https://github.com/skulitom/Pixelbolt). MIT licence; see LICENSE.`,
    '-- Generated by aseprite/build.mjs: every module and the presets in one file, loaded without require or io.',
    'local sources = {}'
  ];
  for (const { name, text } of modules) parts.push(`sources[${JSON.stringify(name)}] = function(...)\n${text.replace(/\s+$/, '')}\nend`);
  parts.push(`sources["presets"] = function(...)\n${presets.replace(/^--[^\n]*\n/, '').replace(/\s+$/, '')}\nend`);
  parts.push(`local cache = {}
local function use(name)
  local m = cache[name]
  if m == nil then
    local load = sources[name]
    if not load then error("Pixelbolt Fluids: missing module " .. tostring(name), 2) end
    m = load(use)
    if m == nil then m = true end
    cache[name] = m
  end
  return m
end
local plugin = use("plugin")
function init(p) plugin.init(p) end
function exit(p) plugin.exit(p) end
`);
  return parts.join('\n');
}

export function manifest() {
  return {
    name: NAME,
    displayName: 'Pixelbolt Fluids',
    description: "Pixelbolt's gas fluid presets (campfire, torch, steam, magic swirl, explosion, smoke, dust) simulated in Aseprite and baked into frames. Free, MIT.",
    version: VERSION,
    author: { name: 'Pixelbolt contributors', url: 'https://github.com/skulitom/Pixelbolt' },
    publisher: 'skulitom',
    license: 'MIT',
    categories: ['Scripts'],
    contributes: { scripts: [{ path: `./${NAME}.lua` }] }
  };
}

// Pixelbolt's own frames for a pre-baked preset: the defaults over 8 seeds, rows of palette keys.
export async function prebake(preset, seeds) {
  const { referenceFrames, initialSettings } = await import(pathToFileURL(join(HERE, 'tools', 'reference.mjs')).href);
  const { values } = initialSettings(preset.source);
  const colours = Object.entries(preset.source.palette).map(([k, hex]) => [k, [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16))]);
  const bakes = {};
  for (const seed of seeds) {
    const r = referenceFrames(preset.source, { values, seed });
    bakes[seed] = {
      width: r.width, height: r.height, loop: r.loop, durations: r.durations,
      frames: r.frames.map(data => {
        let row = '';
        for (let i = 0; i < data.length; i += 4) {
          if (data[i + 3] === 0) { row += '.'; continue; }
          const hit = colours.find(([, c]) => c[0] === data[i] && c[1] === data[i + 1] && c[2] === data[i + 2]);
          if (!hit || data[i + 3] !== 255) throw new Error(`${preset.name}: a pixel outside the palette`);
          row += hit[0];
        }
        return row;
      })
    };
  }
  return { seeds, bakes };
}

function prebakedModule(presets, prebaked) {
  // presetsModule writes the plain presets; pre-baked ones gain a `prebaked` table.
  let text = presetsModule(presets);
  for (const [name, data] of Object.entries(prebaked)) {
    const marker = `    name = ${JSON.stringify(name)},\n`;
    const bakes = Object.entries(data.bakes).map(([seed, b]) => `[${seed}] = ${lua(b, '      ')}`).join(',\n      ');
    text = text.replace(marker, `${marker}    prebaked = {\n      seeds = ${lua(data.seeds)},\n      bakes = {\n      ${bakes}\n      }\n    },\n`);
  }
  return text;
}

// The Lua controls must be the Fluid lab's: same sliders in the same order, labels, ranges, steps, the value at every
// slider position (as a range input snaps it, sliderValue) and each preset's starting values
// (studio/fluid-controls.js FLUID_SLIDERS.gas).
export async function checkControls(exe, presets) {
  const { FLUID_SLIDERS, fluidEffect, sliderValue } = await import(pathToFileURL(join(ROOT, 'studio', 'fluid-controls.js')).href);
  const out = execFileSync(exe, [join(HERE, 'checks', 'controls-dump.lua'), join(DIST, 'presets.lua')], { encoding: 'utf8' });
  const lua = out.trim().split(/\r?\n/).map(line => line.split('\t'));
  const want = [];
  for (const s of FLUID_SLIDERS.gas) want.push(['slider', s.key, s.label, String(s.min), String(s.max), String(s.step)]);
  for (const s of FLUID_SLIDERS.gas) {
    const positions = Math.round((s.max - s.min) / s.step);
    for (let i = 0; i <= positions; i++) want.push(['value', s.key, String(i), String(sliderValue(s, s.min + i * s.step))]);
  }
  for (const p of presets) for (const s of FLUID_SLIDERS.gas) want.push(['initial', p.name, s.key, String(s.initial(fluidEffect(p.source)))]);
  const text = rows => rows.map(r => r.join('\t')).join('\n');
  if (text(lua) !== text(want)) {
    const at = want.findIndex((r, i) => r.join('\t') !== (lua[i] ?? []).join('\t'));
    throw new Error(`extension/controls.lua differs from the Fluid lab's sliders: expected "${want[at]?.join(' ')}", got "${lua[at]?.join(' ')}"`);
  }
}

function commitOf() {
  try { return execFileSync('git', ['rev-parse', '--short=12', 'HEAD'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { return 'unknown'; }
}

export async function build({ luaPath, skipGates = false, log = console.log } = {}) {
  const exe = resolve(luaPath ?? join(HERE, '.tools', process.platform === 'win32' ? 'lua.exe' : 'lua'));
  if (!existsSync(exe)) throw new Error(`no Lua 5.4 interpreter at ${exe}; put one there or pass --lua`);
  const presets = await loadPresets();
  const listed = JSON.parse(readFileSync(join(HERE, 'prebaked.json'), 'utf8'));
  for (const name of listed) if (!presets.some(p => p.name === name)) throw new Error(`prebaked.json names an unknown preset: ${name}`);
  const live = presets.filter(p => !listed.includes(p.name)).map(p => p.name);
  mkdirSync(DIST, { recursive: true });
  const modules = moduleFiles().map(m => ({ ...m, text: readFileSync(m.file, 'utf8') }));
  for (const m of modules) checkModule(m.name, m.text);
  if (!modules.some(m => m.name === 'fluid/compile')) throw new Error('extension/fluid/compile.lua is missing');
  const plainPresets = presetsModule(presets);
  writeFileSync(join(DIST, 'presets.lua'), plainPresets);
  if (!skipGates) {
    await checkControls(exe, presets);
    if (live.length) {
      log(`parity gate for ${live.length} live presets: ${live.join(', ')}`);
      execFileSync(process.execPath, [join(HERE, 'tools', 'parity.mjs'), '--lua', exe, '--min', '100', '--live', live.join(',')], { stdio: 'inherit' });
    }
    log('checks against the stand-in Aseprite API');
    execFileSync(exe, [join(HERE, 'checks', 'run-checks.lua'), join(DIST, 'presets.lua')], { stdio: 'inherit' });
  } else log('gates skipped (--skip-gates): this package is not a release');
  const prebaked = {};
  for (const name of listed) {
    const preset = presets.find(p => p.name === name), seed = preset.source.effects[preset.effect].seed ?? 1;
    prebaked[name] = await prebake(preset, Array.from({ length: 8 }, (_, i) => seed + i));
    log(`pre-baked ${name}: seeds ${prebaked[name].seeds.join(', ')}`);
  }
  const commit = commitOf();
  const script = bundle(modules.map(({ name, text }) => ({ name, text })), prebakedModule(presets, prebaked), commit);
  const scriptFile = join(DIST, `${NAME}.lua`);
  writeFileSync(scriptFile, script);
  execFileSync(exe, [join(HERE, 'checks', 'bundle-smoke.lua'), scriptFile], { stdio: 'inherit' });
  const { createZip } = await import(pathToFileURL(join(ROOT, 'src', 'export.js')).href);
  const files = new Map([
    ['package.json', Buffer.from(JSON.stringify(manifest(), null, 2) + '\n')],
    [`${NAME}.lua`, Buffer.from(script)],
    ['LICENSE', readFileSync(join(HERE, 'LICENSE'))],
    ['README.md', readFileSync(join(HERE, 'README.md'))]
  ]);
  const zip = createZip(files);
  const out = join(DIST, `${NAME}-${VERSION}.aseprite-extension`);
  writeFileSync(out, zip);
  const sha256 = createHash('sha256').update(zip).digest('hex');
  log(`wrote ${relative(ROOT, out)} (${zip.length} bytes) from ${commit}`);
  log(`live: ${live.join(', ') || 'none'}; pre-baked: ${listed.join(', ') || 'none'}`);
  log(`SHA-256 ${sha256}`);
  return { out, sha256, live, prebaked: listed, commit };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const at = process.argv.indexOf('--lua');
  try {
    await build({ luaPath: at > 0 ? process.argv[at + 1] : undefined, skipGates: process.argv.includes('--skip-gates') });
  } catch (error) {
    if (error instanceof PresetError) { console.error(`aseprite build: ${error.message}`); process.exit(1); }
    if (error.status !== undefined) { console.error('aseprite build: a gate failed (see above)'); process.exit(1); }
    console.error(`aseprite build: ${error.message}`);
    process.exit(1);
  }
}
