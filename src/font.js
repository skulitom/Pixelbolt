function composeHangul(character) {
  const code = character.codePointAt(0);
  if (code < 0xAC00 || code > 0xD7A3) return null;
  const cached = HANGUL_CACHE.get(code);
  if (cached) return cached;
  const index = code - 0xAC00, initial = Math.floor(index / 588), [flat, upright] = HANGUL_VOWELS[Math.floor(index % 588 / 28)], final = HANGUL_FINALS[index % 28], closed = index % 28 > 0;
  const grid = Array.from({ length: 9 }, () => Array(9).fill('.'));
  const stamp = (shape, left, top) => shape.split('|').forEach((row, y) => [...row].forEach((cell, x) => { if (cell === '#') grid[top + y][left + x] = '#'; }));
  // The initial: wide over a flat vowel alone, five columns beside or over anything upright; three rows tall where a
  // flat vowel and a final both lie under it, five otherwise. Beside an upright vowel with no final it sits mid-height.
  const wide = flat && !upright, short = flat && closed;
  stamp(HANGUL_INITIALS[`${wide ? 7 : 5}x${short ? 3 : 5}`][initial], wide ? 1 : 0, !flat && !closed ? 2 : 0);
  if (typeof final === 'number') stamp(HANGUL_INITIALS['7x3'][final], 1, 6);
  else if (closed) [...final].forEach((half, k) => stamp(HANGUL_HALVES[half], k * 5, 6));
  if (upright) {
    // Stems run the height of the cell, or down to the final; one tick sits at the middle, two on either side of it.
    const [stems, ticks, count] = HANGUL_UPRIGHT[upright], bottom = closed ? 4 : 8, middle = bottom / 2;
    for (const x of stems) for (let y = 0; y <= bottom; y++) grid[y][x] = '#';
    for (const x of ticks) for (const y of count === 2 ? [middle - 1, middle + 1] : [middle]) grid[y][x] = '#';
  }
  if (flat) {
    // The bar lies across the cell, or under the initial beside an upright part. ㅗ and ㅛ have their ticks above it
    // and ㅜ and ㅠ below, two rows long where there is room. With a final the bar is on the cell's middle row, a
    // row clear of the initial, and a tick below it ends on the row above the final: where the final has ink right
    // under that tick (국: the two would read as one stroke), the bar moves up against the initial instead, and where
    // the final leaves the cells around the tick's end empty (운: ㄴ), the tick is a row longer, so 운 is not 은 plus
    // one pixel.
    const up = 'ㅗㅛ'.includes(flat), down = 'ㅜㅠ'.includes(flat), length = closed ? 1 : 2, right = upright ? 4 : 8, centre = right / 2;
    const ticks = 'ㅛㅠ'.includes(flat) ? [centre - 1, centre + 1] : up || down ? [centre] : [];
    const bar = closed ? (down && ticks.some(x => grid[6][x] === '#') ? 3 : 4) : up ? 8 : down ? 6 : 7;
    for (let x = 0; x <= right; x++) grid[bar][x] = '#';
    const room = closed && down && bar === 4 && ticks.every(x => [x - 1, x, x + 1].every(c => grid[6][c] !== '#') && grid[7][x] !== '#');
    for (const x of ticks) for (let k = 1; k <= length + (room ? 1 : 0); k++) grid[bar + (up ? -k : k)][x] = '#';
  }
  const glyph = { width: 9, rows: ['.........', ...grid.map(row => row.join(''))] };
  if (HANGUL_CACHE.size < 2048) HANGUL_CACHE.set(code, glyph);
  return glyph;
}
function lookupGlyph(character) {
  return GLYPHS.get(character) ?? composeHangul(character);
}
export function hasGlyph(character) {
  if (typeof character !== 'string') return false;
  const normalized = character.normalize('NFC');
  const chars = [...normalized];
  return chars.length === 1 && Boolean(lookupGlyph(chars[0]));
}
// Every character in the static font table, in code order (Korean Hangul U+AC00..U+D7A3 are composed on demand).
export const FONT_CHARACTERS = [...GLYPHS.keys()].sort().join('');

// Lays text out as rows of "#" and ".". Lines are split at "\n"; `spacing` is the gap between glyphs, `lineHeight` the
// distance from one line's top to the next, and `align` how shorter lines sit in the block. `top` is where the block
// starts relative to the top of the first line's capitals: 0, -2 when an accented capital on the first line needs
// the rows above, or -1 for a Hangul syllable or an ideograph, whose cell starts one row up. On later lines those
// rows are the gap between lines.
// `reject(message)` is called for text the font cannot draw and must throw.
export function layoutText(text, { spacing = 1, lineHeight = 10, align = 'left' } = {}, reject = message => { throw new Error(message); }) {
  // Composed forms, so that "e" followed by a combining accent is the one character "é".
  const lines = text.normalize('NFC').split('\n').map(line => {
    const glyphs = [...line].map(character => lookupGlyph(character) ?? reject(`no glyph for ${JSON.stringify(character)}; the built-in font draws printable ASCII, western European accented letters, Cyrillic, Japanese Kana, Korean Hangul, ${IDEOGRAPH_COUNT} ideographs of game menus (no others) and symbols (${'¡¿«»‹›°©®£€¥¢·×÷±–—…‘’‚“”„•'})`));
    return { text: line, glyphs, width: glyphs.reduce((sum, glyph) => sum + glyph.width, 0) + spacing * Math.max(0, glyphs.length - 1) };
  });
  // Rows needed above the first line, by what each line's glyphs draw there (two for an accent, one for a 9×9 cell):
  // a later line only reaches there when lines are closer than that.
  const reach = glyph => glyph.rows[0].includes('#') ? 2 : glyph.rows[1].includes('#') ? 1 : 0;
  const above = Math.max(0, ...lines.map((line, index) => Math.max(0, ...line.glyphs.map(reach)) - index * lineHeight));
  const width = Math.max(1, ...lines.map(line => line.width)), height = above + (lines.length - 1) * lineHeight + FONT_HEIGHT, cells = Array.from({ length: height }, () => Array(width).fill('.'));
  for (const [index, line] of lines.entries()) {
    let x = align === 'center' ? Math.floor((width - line.width) / 2) : align === 'right' ? width - line.width : 0;
    for (const glyph of line.glyphs) {
      for (let y = 0; y < ROWS; y++) {
        const row = above - FONT_ABOVE + index * lineHeight + y;
        if (row >= 0) for (let i = 0; i < glyph.width; i++) if (glyph.rows[y][i] === '#') cells[row][x + i] = '#';
      }
      x += glyph.width + spacing;
    }
  }
  return { width, height, top: above ? -above : 0, rows: cells.map(row => row.join('')), lines: lines.map(line => ({ text: line.text, width: line.width })) };
}
// The size a text block will have, for placing it: { width, height, top, lines: [{ text, width }] }.
export function measureText(text, options) { const { width, height, top, lines } = layoutText(text, options); return { width, height, top, lines }; }
