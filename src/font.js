const VOWEL_KIND = [0, 0, 0, 0, 0, 0, 0, 0, 1, 2, 2, 2, 1, 1, 2, 2, 2, 1, 1, 2, 0];
const HANGUL_CACHE = new Map();

function stampBits(grid, shape, ox, oy) {
  const rows = shape.split('|');
  for (let y = 0; y < rows.length; y++) {
    const r = oy + y;
    if (r < 0 || r >= 8) continue;
    for (let x = 0; x < rows[y].length; x++) {
      const c = ox + x;
      if (c >= 0 && c < 8 && rows[y][x] === '#') grid[r][c] = '#';
    }
  }
}
function drawVerticalVowel(grid, v, top, bottom) {
  const mid = top + Math.floor((bottom - top) / 2);
  const vline = (x, y0, y1) => { for (let y = y0; y <= y1; y++) grid[y][x] = '#'; };
  // Right-side column(s): x = 5..7
  if (v === 0) { vline(5, top, bottom); grid[mid][6] = '#'; grid[mid][7] = '#'; } // ㅏ
  else if (v === 1) { vline(5, top, bottom); grid[mid][6] = '#'; vline(7, top, bottom); } // ㅐ
  else if (v === 2) { vline(5, top, bottom); grid[top + 1][6] = '#'; grid[top + 1][7] = '#'; grid[Math.max(top + 2, bottom - 1)][6] = '#'; grid[Math.max(top + 2, bottom - 1)][7] = '#'; } // ㅑ
  else if (v === 3) { vline(5, top, bottom); grid[top + 1][6] = '#'; grid[Math.max(top + 2, bottom - 1)][6] = '#'; vline(7, top, bottom); } // ㅒ
  else if (v === 4) { vline(6, top, bottom); grid[mid][5] = '#'; grid[mid][4] = '#'; } // ㅓ
  else if (v === 5) { vline(5, top, bottom); grid[mid][4] = '#'; vline(7, top, bottom); } // ㅔ
  else if (v === 6) { vline(6, top, bottom); grid[top + 1][5] = '#'; grid[Math.max(top + 2, bottom - 1)][5] = '#'; } // ㅕ
  else if (v === 7) { vline(5, top, bottom); grid[top + 1][4] = '#'; grid[Math.max(top + 2, bottom - 1)][4] = '#'; vline(7, top, bottom); } // ㅖ
  else if (v === 20) { vline(6, top, bottom); } // ㅣ
}
function drawHorizontalVowel(grid, v, row, x0, x1) {
  for (let x = x0; x <= x1; x++) grid[row][x] = '#';
  const cx = Math.floor((x0 + x1) / 2);
  if (v === 8) grid[row - 1][cx] = '#'; // ㅗ
  else if (v === 12) { grid[row - 1][cx - 1] = '#'; grid[row - 1][cx + 1] = '#'; } // ㅛ
  else if (v === 13) grid[row + 1][cx] = '#'; // ㅜ
  else if (v === 17) { grid[row + 1][cx - 1] = '#'; grid[row + 1][cx + 1] = '#'; } // ㅠ
}
function composeHangul(character) {
  const code = character.codePointAt(0);
  if (code < 0xAC00 || code > 0xD7A3) return null;
  const cached = HANGUL_CACHE.get(code);
  if (cached) return cached;
  const index = code - 0xAC00, L = Math.floor(index / 588), V = Math.floor((index % 588) / 28), T = index % 28;
  const grid = Array.from({ length: 8 }, () => Array(8).fill('.'));
  const kind = VOWEL_KIND[V];
  if (kind === 0) {
    stampBits(grid, CHO_S[L], 0, T ? 0 : 1);
    drawVerticalVowel(grid, V, 0, T ? 3 : 6);
  } else if (kind === 1) {
    const hRow = V === 8 || V === 12 ? (T ? 4 : 5) : V === 13 || V === 17 ? (T ? 3 : 4) : (T ? 3 : 5);
    stampBits(grid, CHO_W[L], 1, T ? 0 : 0);
    drawHorizontalVowel(grid, V, hRow, 0, 7);
  } else {
    // Compound vowels: ㅘ(9) ㅙ(10) ㅚ(11) ㅝ(14) ㅞ(15) ㅟ(16) ㅢ(19)
    const compactCho = L === 11 ? '.##.|#..#|.##.' : L === 6 ? '####|#..#|####' : L === 3 ? '####|#...|####' : CHO_S[L].split('|').slice(0, 3).join('|');
    stampBits(grid, T ? compactCho : CHO_S[L], 0, 0);
    const hBase = V <= 11 ? 8 : V <= 16 ? 13 : 18;
    const hRow = hBase === 8 ? (T ? 4 : 5) : hBase === 13 ? (T ? 3 : 4) : (T ? 4 : 5);
    drawHorizontalVowel(grid, hBase, hRow, 0, 4);
    const vPart = V === 9 ? 0 : V === 10 ? 1 : V === 14 ? 4 : V === 15 ? 5 : 20;
    drawVerticalVowel(grid, vPart, 0, T ? 4 : 6);
  }
  if (T) stampBits(grid, JONG[T], 0, 5);
  // Trim outer empty columns so narrow syllables sit naturally beside other glyphs.
  const inked = Array.from({ length: 8 }, (_, x) => grid.some(row => row[x] === '#'));
  const left = Math.max(0, inked.indexOf(true)), right = Math.max(left, inked.lastIndexOf(true));
  const width = right - left + 1;
  const pad = '.'.repeat(width);
  const rows = [pad, pad, ...grid.map(row => row.slice(left, right + 1).join(''))];
  const glyph = { width, rows };
  if (HANGUL_CACHE.size < 2048) HANGUL_CACHE.set(code, glyph);
  return glyph;
}
function lookupGlyph(character) {
  return GLYPHS.get(character) ?? composeHangul(character);
}
export function hasGlyph(character) {
  if (typeof character !== 'string') return false;
  const normalized = character.normalize('NFC');
  const chars = [...normalized];
  return chars.length === 1 && Boolean(lookupGlyph(chars[0]));
}
